export function calculateResults(answers) {
  const scores = {}
  hustles.forEach(h => { scores[h.id] = 0 })

  questions.forEach(q => {
    const answer = answers[q.id]
    if (!answer) return

    const selectedIds = Array.isArray(answer) ? answer : [answer]
    selectedIds.forEach(selectedId => {
      const option = q.options.find(o => o.id === selectedId)
      if (!option) return
      Object.entries(option.scores).forEach(([hustleId, points]) => {
        if (scores[hustleId] !== undefined) {
          scores[hustleId] += points
        }
      })
    })
  })

  return hustles
    .map(h => ({ ...h, score: scores[h.id] }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
}
